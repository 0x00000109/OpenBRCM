#define OB_A7089_POSTCAL_COUNT 220

int ob_acphy_a7089_postcal_prefix_run(const struct ob_a7089_cal_ops *ops,
				      void *ctx,
				      struct ob_a7089_cal_result *result)
{
	u16 tmp; unsigned int i; int ret;
	if (!result) return -22;
	result->callback_count = 0; result->logical_event_count = 0;
	result->row_count = 0; result->hardware_ready = false;
	if (!ops || !ops->write16 || !ops->read16) return -22;
	for (i = 0; i < OB_A7089_POSTCAL_COUNT; i++) {
		const struct ob_a7089_postcal_op *o = &ob_a7089_postcal[i];
		if (o->op)
			ret = ops->read16(ctx, (u8)(i + 1), o->reg, &tmp);
		else
			ret = ops->write16(ctx, (u8)(i + 1), o->reg, o->value);
		if (ret) return ret;
		result->callback_count++; result->logical_event_count++;
	}
	return 0;
}

