int ob_acphy_a7089_radio_cal_prefix_run(const struct ob_a7089_cal_ops *ops,
					void *ctx,
					struct ob_a7089_cal_result *result)
{
	struct ob_a7089_cal_result done;
	unsigned int r, i;
	int ret;

	if (!result)
		return -22;
	result->callback_count = 0;
	result->logical_event_count = 0;
	result->row_count = 0;
	result->hardware_ready = false;
	if (!ops || !ops->write16)
		return -22;
	done.callback_count = 0;
	done.logical_event_count = 0;
	done.row_count = 0;

	for (r = 0; r < OB_A7089_CAL_ROW_COUNT; r++) {
		for (i = 0; i < OB_A7089_CAL_REG_COUNT; i++) {
			ret = ops->write16(ctx, (u8)((done.callback_count + 1) & 0xff),
					   ob_a7089_cal_regs[i],
					   ob_a7089_cal_rows[r][i]);
			if (ret)
				return ret;
			done.callback_count++;
			done.logical_event_count++;
		}
		done.row_count++;
	}
	*result = done;
	return 0;
}

