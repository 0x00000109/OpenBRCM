static bool bcm43xx_use_alt_reg(u32 chip_id)
{
	return chip_id == 0x4352 || chip_id == 0x4360 ||
	       chip_id == 0xa9c4 || chip_id == 0xaa06;
}

static const struct bcm43xx_radio_field *
bcm43xx_fields_for(enum bcm43xx_chan_tuning_kind kind, size_t *count, u16 *tail)
{
	switch (kind) {
	case BCM43XX_ROW_2069:
		*count = sizeof(fields_2069) / sizeof(fields_2069[0]);
		*tail = BCM43XX_CHAN_TUNING_STRIDE_2069 - 12;
		return fields_2069;
	case BCM43XX_ROW_GE25:
		*count = sizeof(fields_ge25) / sizeof(fields_ge25[0]);
		*tail = BCM43XX_CHAN_TUNING_STRIDE_GE25 - 12;
		return fields_ge25;
	case BCM43XX_ROW_LEGACY:
		*count = sizeof(fields_legacy) / sizeof(fields_legacy[0]);
		*tail = BCM43XX_CHAN_TUNING_STRIDE_LEGACY - 12;
		return fields_legacy;
	default:
		return NULL;
	}
}

int bcm43xx_apply_chan_tuning(enum bcm43xx_chan_tuning_kind kind,
			      const void *row,
			      const struct bcm43xx_chan_tuning_io *io)
{
	const struct bcm43xx_radio_field *fields;
	const u8 *base = row;
	size_t count = 0;
	u16 tail = 0;
	bool alt;
	size_t i;

	if (!row || !io || !io->write_radio_reg || !io->phy_reg_write)
		return -EINVAL;
	fields = bcm43xx_fields_for(kind, &count, &tail);
	if (!fields)
		return -EINVAL;
	alt = bcm43xx_use_alt_reg(io->chip_id);
	for (i = 0; i < count; i++) {
		u16 value;
		memcpy(&value, base + fields[i].offset, sizeof(value));
		io->write_radio_reg(io->ctx,
			alt ? fields[i].reg_alt : fields[i].reg_default, value);
	}
	for (i = 0; i < BCM43XX_CHAN_TUNING_BW_COUNT; i++) {
		u16 value;
		memcpy(&value, base + tail + 2 * i, sizeof(value));
		io->phy_reg_write(io->ctx, BCM43XX_PHY_BW1A + i, value);
	}
	return 0;
}

static const struct bcm43xx_chan_tuning_table *
bcm43xx_select_table(const struct bcm43xx_chan_tuning_env *env,
		     const struct bcm43xx_chan_tuning_tables *tables)
{
	u8 rev = env->radio_rev;

	switch (env->radio_class) {
	case 0:
		if (rev < 3 || rev > 8)
			return NULL;
		return &tables->mode0[rev - 3];
	case 1:
		if (rev < 0x10 || rev > 0x1a)
			return NULL;
		return env->refclk_hz == BCM43XX_REFCLK_40MHZ ?
		       &tables->mode1_40[rev - 0x10] :
		       &tables->mode1[rev - 0x10];
	case 2:
		if (rev > 0x3f || !((1ULL << rev) & BCM43XX_MODE2_REV_MASK))
			return NULL;
		return env->refclk_hz == BCM43XX_REFCLK_40MHZ ?
		       &tables->mode2_40mhz_ref : &tables->mode2_other_ref;
	default:
		return NULL;
	}
}

int bcm43xx_get_chan_tuning_row(const struct bcm43xx_chan_tuning_env *env,
				const struct bcm43xx_chan_tuning_tables *tables,
				u16 chanspec, u16 expected_freq_mhz,
				u32 *code, const void **row74,
				const void **row5e, const void **row60,
				const void **row5e_mode2)
{
	const struct bcm43xx_chan_tuning_table *table;
	const void **selected = NULL;
	u16 channel;
	u16 i;

	if (!env || !tables)
		return -EINVAL;
	if (row74) *row74 = NULL;
	if (row5e) *row5e = NULL;
	if (row60) *row60 = NULL;
	if (row5e_mode2) *row5e_mode2 = NULL;
	if (code) *code = 0;

	table = bcm43xx_select_table(env, tables);
	if (!table || !table->rows || !table->count ||
	    table->stride < sizeof(struct bcm43xx_chan_tuning_hdr))
		return -ENOENT;
	if (env->radio_class == 0)
		selected = row74;
	else if (env->radio_class == 1)
		selected = (env->radio_rev == 0x19 || env->radio_rev == 0x1a) ? row60 : row5e;
	else
		selected = row5e_mode2;

	channel = bcm43xx_chan_tuning_channel(chanspec);
	for (i = 0; i < table->count; i++) {
		const u8 *row = (const u8 *)table->rows + (size_t)i * table->stride;
		u8 row_channel;
		u16 row_freq;

		memcpy(&row_channel, row, sizeof(row_channel));
		memcpy(&row_freq, row + 2, sizeof(row_freq));
		if (row_channel != channel)
			continue;
		if (expected_freq_mhz && row_freq != expected_freq_mhz)
			continue;
		if (code) *code = row_freq;
		if (selected) *selected = row;
		return 0;
	}
	return -ENOENT;
}
